export interface AILabsOpportunity {
  id: string;
  name: string;
  clientId: null;
  stage: string;          // legacy generic stage (kept for type compat)
  value: number;
  probability: number;
  expectedCloseDate: string | null;
  ownerId: null;
  lastInteractionAt: string;
  createdAt: string;
  updatedAt: string;
  // ---- AI Experience Labs fields ----
  aiStage: string;
  contactName: string;
  contactTitle: string;
  contactEmail: string;
  trinamixOwner: string;
  dealRating: number;          // 0-5
  copyOracle: boolean;
  emailOwner: string;
  interestedScenarios: string[];
  followUpNotes: string;
  nextSteps: string;
  lastReviewed: string | null;
  urgentNotes: string;
}

function opp(
  id: string,
  name: string,
  aiStage: string,
  trinamixOwner: string,
  dealRating: number,
  contactName: string,
  contactEmail: string,
  scenarios: string[],
  followUpNotes = '',
  nextSteps = '',
  contactTitle = '',
  copyOracle = false,
  emailOwner = 'Account rep',
  urgentNotes = '',
  lastReviewed: string | null = null,
): AILabsOpportunity {
  // Estimate CRM value from rating
  const valueMap: Record<number, number> = { 0: 0, 1: 25000, 2: 75000, 3: 150000, 4: 250000, 5: 500000 };
  const probMap: Record<string, number> = {
    negotiation_sow: 75, deal_closed: 100, enabling_ai: 60,
    workshop_executed: 40, workshop_scheduled: 30, preworkshop_scheduled: 20,
    pending_workshop: 15, add_oracle: 20, reply_sent: 10, interest_received: 10,
    intro_sent: 5, not_interested: 0, not_legit: 0,
  };
  const legacyMap: Record<string, string> = {
    intro_sent: 'qualify', interest_received: 'qualify', reply_sent: 'qualify',
    preworkshop_scheduled: 'discover', pending_workshop: 'discover',
    workshop_scheduled: 'discover', add_oracle: 'discover',
    workshop_executed: 'propose', enabling_ai: 'propose',
    negotiation_sow: 'negotiate', deal_closed: 'negotiate',
    not_interested: 'closed_lost', not_legit: 'closed_lost',
  };
  return {
    id, name, clientId: null,
    stage: legacyMap[aiStage] ?? 'qualify',
    value: valueMap[dealRating] ?? 0,
    probability: probMap[aiStage] ?? 10,
    expectedCloseDate: null,
    ownerId: null,
    lastInteractionAt: new Date(Date.now() - Math.random() * 30 * 86400000).toISOString(),
    createdAt: '2025-09-01T00:00:00.000Z',
    updatedAt: new Date().toISOString(),
    aiStage, contactName, contactTitle, contactEmail,
    trinamixOwner, dealRating, copyOracle, emailOwner,
    interestedScenarios: scenarios, followUpNotes, nextSteps,
    lastReviewed, urgentNotes,
  };
}

